// Copies the Pyodide runtime into public/pyodide/v<version>/ (a versioned,
// immutable path) and records the version for the app.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const pkgDir = join(root, "node_modules", "pyodide")
const { version } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"))
const files = ["pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"]

const outRoot = join(root, "public", "pyodide")
rmSync(outRoot, { recursive: true, force: true })
const out = join(outRoot, `v${version}`)
mkdirSync(out, { recursive: true })
for (const file of files) copyFileSync(join(pkgDir, file), join(out, file))

writeFileSync(
  join(root, "src", "generated", "pyodide.ts"),
  `// Generated by scripts/copy-pyodide.mjs — do not edit.\nexport const PYODIDE_VERSION = "${version}"\n`,
)
console.log(`pyodide ${version} → public/pyodide/v${version}/`)
